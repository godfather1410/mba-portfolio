import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns

# Ensure data is loaded (if running in a separate session)
# df = pd.read_csv("global_air_quality_2014_2025.csv")

# Set global styles
sns.set_theme(style="whitegrid")
plt.rcParams.update({'font.size': 11, 'axes.labelsize': 12, 'axes.titlesize': 14})

# =====================================================================
# GRAPH 5: TOP 10 COUNTRIES BY AVERAGE AQI (Bar Plot)
# Categorical comparison of pollution levels
# =====================================================================
print("Generating Graph 5: Top 10 Countries by Avg AQI...")
plt.figure(figsize=(10, 6))
top_countries = df.groupby('Country')['AQI'].mean().sort_values(ascending=False).head(10)
sns.barplot(x=top_countries.values, y=top_countries.index, palette="Reds_r")
plt.title('Top 10 Most Polluted Countries (By Average AQI)')
plt.xlabel('Average Air Quality Index (AQI)')
plt.ylabel('Country')
plt.tight_layout()
plt.savefig('5_top_countries_aqi.png', dpi=300)
plt.show()

# =====================================================================
# GRAPH 6: BOX PLOT - AQI DISTRIBUTION FOR TOP 5 COUNTRIES
# Excellent for showcasing data spread, medians, and outliers
# =====================================================================
print("Generating Graph 6: Box Plot of AQI for Top Countries...")
plt.figure(figsize=(12, 6))
# Filter data for the top 5 countries found above to keep the chart clean
top_5_names = top_countries.head(5).index
df_top5 = df[df['Country'].isin(top_5_names)]

sns.boxplot(data=df_top5, x='Country', y='AQI', palette='Set2', flierprops={"marker": "x", "markerfacecolor": "red", "markersize": 4})
plt.title('AQI Distribution and Outliers Across Top 5 Countries')
plt.xlabel('Country')
plt.ylabel('Air Quality Index (AQI)')
plt.tight_layout()
plt.savefig('6_aqi_outliers_boxplot.png', dpi=300)
plt.close() # Saves memory in Colab, download via files tab

# =====================================================================
# GRAPH 7: VIOLIN PLOT - HUMIDITY SHAPE BY AQI BUCKETS
# Shows how the structural "shape" of humidity changes with pollution severity
# =====================================================================
print("Generating Graph 7: Violin Plot of Humidity vs AQI Buckets...")
plt.figure(figsize=(12, 6))
# Select a few key buckets to avoid cluttering the chart
target_buckets = ['Good', 'Moderate', 'Unhealthy', 'Hazardous']
df_filtered_buckets = df[df['AQI_Bucket'].isin(target_buckets)]

sns.violinplot(data=df_filtered_buckets, x='AQI_Bucket', y='Humidity (%)', order=target_buckets, palette='coolwarm')
plt.title('Structural Distribution Shape of Humidity across Key AQI Buckets')
plt.xlabel('AQI Category')
plt.ylabel('Humidity (%)')
plt.tight_layout()
plt.savefig('7_humidity_violin_plot.png', dpi=300)
plt.close()

# =====================================================================
# GRAPH 8: HEXBIN DENSITY PLOT - PM2.5 vs PM10 (All 330k+ Rows)
# Alternative to scatter plots; handles heavy data density without lagging
# =====================================================================
print("Generating Graph 8: Hexbin Plot for PM2.5 vs PM10...")
plt.figure(figsize=(10, 8))
# Filter out extreme extreme outliers just for a cleaner visual window
df_clean_limits = df[(df['PM2.5 (ug/m3)'] < 200) & (df['PM10 (ug/m3)'] < 300)]

plt.hexbin(df_clean_limits['PM2.5 (ug/m3)'], df_clean_limits['PM10 (ug/m3)'], gridsize=40, cmap='YlOrRd', mincnt=1)
plt.colorbar(label='Count of Observations in Bin')
plt.title('Data Concentration Density: PM2.5 vs PM10')
plt.xlabel('PM2.5 (ug/m³)')
plt.ylabel('PM10 (ug/m³)')
plt.tight_layout()
plt.savefig('8_pm25_vs_pm10_hexbin.png', dpi=300)
plt.close()

print("All additional graphs generated successfully! Refresh your left files tab to download them.")

